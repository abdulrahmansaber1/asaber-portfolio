export function getProjectDescription(
  project: { title: string; description: string },
  locale: string,
) {
  return locale === "ar"
    ? arabicDescriptions[project.title] ?? project.description
    : project.description
}

export function getProjectSummary(
  project: { title: string; description: string; shortBrief?: string },
  locale: string,
) {
  return locale === "ar"
    ? arabicDescriptions[project.title] ?? project.shortBrief ?? project.description
    : project.shortBrief || project.description
}

export function getProjectFeatures(features: string[] | undefined, locale: string) {
  if (!features || locale !== "ar") return features
  return features.map((feature) => arabicFeatures[feature] ?? feature)
}
